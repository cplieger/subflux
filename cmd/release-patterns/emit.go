package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"maps"
	"slices"
	"strconv"
	"strings"
)

func parseGo(name string) (*ast.File, error) {
	return parser.ParseFile(token.NewFileSet(), name, nil, 0)
}

// constBlocks returns each const declaration's specs.
func constBlocks(f *ast.File) [][]*ast.ValueSpec {
	var blocks [][]*ast.ValueSpec
	for _, decl := range f.Decls {
		gd, ok := decl.(*ast.GenDecl)
		if !ok || gd.Tok != token.CONST {
			continue
		}
		var specs []*ast.ValueSpec
		for _, spec := range gd.Specs {
			if vs, ok := spec.(*ast.ValueSpec); ok {
				specs = append(specs, vs)
			}
		}
		blocks = append(blocks, specs)
	}
	return blocks
}

func readConsts(name string) (map[string]string, error) {
	f, err := parseGo(name)
	if err != nil {
		return nil, err
	}
	consts := map[string]string{}
	for _, vs := range slices.Concat(constBlocks(f)...) {
		for i, n := range vs.Names {
			if i >= len(vs.Values) {
				break
			}
			if lit, ok := vs.Values[i].(*ast.BasicLit); ok && lit.Kind == token.STRING {
				if v, err := strconv.Unquote(lit.Value); err == nil {
					consts[n.Name] = v
				}
			}
		}
	}
	return consts, nil
}

// readSourceNames lists the constants of type Source, so a manifest naming
// a missing one is refused instead of generating code that does not build.
// The block's first spec carries the type; the rest repeat it by iota.
func readSourceNames(name string) (map[string]bool, error) {
	f, err := parseGo(name)
	if err != nil {
		return nil, err
	}
	names := map[string]bool{}
	for _, block := range constBlocks(f) {
		if id, ok := block[0].Type.(*ast.Ident); !ok || id.Name != "Source" {
			continue
		}
		for _, vs := range block {
			for _, n := range vs.Names {
				names[n.Name] = true
			}
		}
	}
	if len(names) == 0 {
		return nil, fmt.Errorf("%s: no Source constants", name)
	}
	return names, nil
}

// readOverrides reads overrides.go's override values: name to the hash of
// the upstream text each ports.
func readOverrides(name string) (map[string]string, error) {
	f, err := parseGo(name)
	if err != nil {
		return nil, err
	}
	out := map[string]string{}
	ast.Inspect(f, func(n ast.Node) bool {
		vs, ok := n.(*ast.ValueSpec)
		if !ok {
			return true
		}
		for i, id := range vs.Names {
			if i < len(vs.Values) {
				if sum, ok := overrideUpstream(vs.Values[i]); ok {
					out[id.Name] = sum
				}
			}
		}
		return false
	})
	if len(out) == 0 {
		return nil, fmt.Errorf("%s: no override values", name)
	}
	return out, nil
}

// overrideUpstream reads the upstream field of an override{...} literal.
func overrideUpstream(e ast.Expr) (string, bool) {
	lit, ok := e.(*ast.CompositeLit)
	if !ok {
		return "", false
	}
	if typ, ok := lit.Type.(*ast.Ident); !ok || typ.Name != "override" {
		return "", false
	}
	for _, elt := range lit.Elts {
		field, ok := elt.(*ast.KeyValueExpr)
		if !ok {
			continue
		}
		id, idOK := field.Key.(*ast.Ident)
		val, valOK := field.Value.(*ast.BasicLit)
		if idOK && valOK && id.Name == "upstream" {
			sum, err := strconv.Unquote(val.Value)
			return sum, err == nil
		}
	}
	return "", false
}

// emit writes patterns_gen.go; every value goes through Go quoting.
func (g *generator) emit() ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by release-patterns generate; DO NOT EDIT.\n\n")
	b.WriteString("// Imported from patterns.manifest.json at:\n")
	for _, name := range slices.Sorted(maps.Keys(g.m.Upstreams)) {
		repo, pin := g.ref(name)
		fmt.Fprintf(&b, "//   - %s %s\n", repo, pin)
	}
	b.WriteString("\npackage release\n\nimport \"github.com/cplieger/subflux/internal/release/netregex\"\n\nvar symbolTable = []symbolEntry{\n")
	for i := range g.symbols {
		g.emitSymbol(&b, &g.symbols[i])
	}
	b.WriteString("}\n\nvar formatTable = []formatEntry{\n")
	for i := range g.formats {
		g.emitFormat(&b, &g.formats[i])
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}

// emitSymbol writes one entry, its provenance in the comment above it.
func (g *generator) emitSymbol(b *bytes.Buffer, s *genSymbol) {
	d := s.decl
	repo, _ := g.ref(d.Upstream)
	fmt.Fprintf(b, "// %s: %s %s %s, %s\n", d.ID, repo, d.Path, d.Symbol, s.rule)
	if len(s.members) > 0 {
		fmt.Fprintf(b, "// members %s\n", strings.Join(s.members, ", "))
	}
	fmt.Fprintf(b, "{id: %s,\n", quote(d.ID))
	switch {
	case s.override != "":
		fmt.Fprintf(b, "override: &%s,\n", s.override)
	case s.pattern != "":
		fmt.Fprintf(b, "pattern: %s,\n", quote(s.pattern))
		fmt.Fprintf(b, "options: netregex.Options{IgnoreCase: %t, IgnorePatternWhitespace: %t},\n", s.options.IgnoreCase, s.options.IgnorePatternWhitespace)
	}
	if d.Kind == kindReplace {
		fmt.Fprintf(b, "replacement: %s,\n", quote(s.replacement))
	}
	if len(d.Groups) > 0 {
		b.WriteString("groups: map[string]Source{")
		for _, k := range slices.Sorted(maps.Keys(d.Groups)) {
			fmt.Fprintf(b, "%s: %s, ", quote(k), d.Groups[k])
		}
		b.WriteString("},\n")
	}
	if len(s.values) > 0 {
		b.WriteString("values: []string{")
		for _, v := range s.values {
			b.WriteString(quote(v) + ", ")
		}
		b.WriteString("},\n")
	}
	b.WriteString("},\n")
}

func (g *generator) emitFormat(b *bytes.Buffer, f *genFormat) {
	repo, _ := g.ref("trash")
	fmt.Fprintf(b, "// %s: %s %s, trash_id %s\n", f.decl.ID, repo, f.file.Path, f.file.TrashID)
	fmt.Fprintf(b, "{id: %s, label: %s, arr: %s, specs: []specEntry{\n", quote(f.decl.ID), quote(f.decl.Label), quote(f.arr))
	for i := range f.specs {
		s := &f.specs[i]
		fmt.Fprintf(b, "// %s: %s\n", s.spec.Name, s.rule)
		fmt.Fprintf(b, "{kind: %s, negate: %t, required: %t,\n", quote(s.kind), s.spec.Negate, s.spec.Required)
		if s.pattern != "" {
			fmt.Fprintf(b, "pattern: %s,\n", quote(s.pattern))
		}
		if len(s.sources) > 0 {
			fmt.Fprintf(b, "sources: []Source{%s},\n", strings.Join(s.sources, ", "))
		}
		b.WriteString("},\n")
	}
	b.WriteString("}},\n")
}

// quote prefers a raw string for text with escapes, which keeps a generated
// pattern's regex escapes readable.
func quote(s string) string {
	if strings.ContainsAny(s, `\"`) && strconv.CanBackquote(s) {
		return "`" + s + "`"
	}
	return strconv.Quote(s)
}
