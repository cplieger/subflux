//go:build ignore

// gen writes tables_gen.go from ICU4C's csrsbcs.cpp and csrmbcs.cpp at the
// pinned commit: every byte map, trigram table and common-character list but
// the EBCDIC ones.
package main

import (
	"bytes"
	"cmp"
	"fmt"
	"go/format"
	"io"
	"log"
	"net/http"
	"os"
	"regexp"
	"slices"
	"strconv"
	"strings"
	"time"
)

const (
	commit = "560e6db559a4a836a016b762051eee00d56e3d76"
	srcURL = "https://raw.githubusercontent.com/unicode-org/icu/" + commit + "/icu4c/source/i18n/"
)

// licenceHeader is the upstream files' own notice, which the copied tables carry.
const licenceHeader = "// © 2016 and later: Unicode, Inc. and others.\n" +
	"// License & terms of use: https://www.unicode.org/copyright.html\n" +
	"// Copyright (C) 2005-2016, International Business Machines Corporation and others. All Rights Reserved.\n\n"

var (
	plainArray = regexp.MustCompile(`(?s)static const (uint8_t|int32_t|uint16_t) (\w+)\s*\[\]\s*=\s*\{(.*?)\};`)
	langArray  = regexp.MustCompile(`(?s)static const NGramsPlusLang (\w+)\[\]\s*=\s*\{(.*?)\n\};`)
	langEntry  = regexp.MustCompile(`(?s)\{\s*\{(.*?)\},\s*"(\w+)"\s*\}`)
	hexValue   = regexp.MustCompile(`0x[0-9A-Fa-f]+`)
	lineNoise  = regexp.MustCompile(`//[^\n]*`)
)

func main() {
	sbcs, mbcs := fetch("csrsbcs.cpp"), fetch("csrmbcs.cpp")
	var out bytes.Buffer
	out.WriteString(licenceHeader)
	fmt.Fprintf(&out, "// Code generated by gen.go from ICU4C %s (csrsbcs.cpp, csrmbcs.cpp). DO NOT EDIT.\n\n", commit[:7])
	out.WriteString("//go:generate go run gen.go\n\npackage icu\n\n")
	for _, m := range plainArray.FindAllStringSubmatch(sbcs+mbcs, -1) {
		typ, name, body := m[1], m[2], m[3]
		if strings.Contains(name, "IBM4") || name == "unshapeMap_IBM420" {
			continue
		}
		values := hexValue.FindAllString(lineNoise.ReplaceAllString(body, ""), -1)
		switch typ {
		case "uint8_t":
			check(name, len(values) == 256)
			fmt.Fprintf(&out, "var %s = [256]byte{%s}\n\n", goName(name), join(values))
		case "int32_t":
			check(name, len(values) == 64 && sorted(values))
			fmt.Fprintf(&out, "var %s = [64]int32{%s}\n\n", goName(name), join(values))
		case "uint16_t":
			check(name, len(values) > 0 && sorted(values))
			fmt.Fprintf(&out, "var %s = [...]uint16{%s}\n\n", goName(name), join(values))
		}
	}
	for _, m := range langArray.FindAllStringSubmatch(sbcs, -1) {
		fmt.Fprintf(&out, "var %s = [...]langNGrams{\n", goName(m[1]))
		entries := langEntry.FindAllStringSubmatch(m[2], -1)
		check(m[1], len(entries) > 0)
		for _, e := range entries {
			values := hexValue.FindAllString(e[1], -1)
			check(m[1]+"/"+e[2], len(values) == 64 && sorted(values))
			fmt.Fprintf(&out, "{%q, [64]int32{%s}},\n", e[2], join(values))
		}
		out.WriteString("}\n\n")
	}
	src, err := format.Source(out.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("tables_gen.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
}

// goName keeps ICU's name in Go's case: charMap_8859_1 becomes charMap8859_1
// and ngrams_8859_5_ru ngrams8859_5Ru, so each table is found upstream by name.
func goName(icu string) string {
	parts := strings.Split(icu, "_")
	name := parts[0]
	for i, p := range parts[1:] {
		switch {
		case i > 0 && isDigit(p[0]) && isDigit(parts[i][len(parts[i])-1]):
			name += "_" + p
		case isDigit(p[0]):
			name += p
		default:
			name += strings.ToUpper(p[:1]) + p[1:]
		}
	}
	return name
}

func isDigit(b byte) bool { return '0' <= b && b <= '9' }

// join lays out values sixteen to a line, as upstream does.
func join(values []string) string {
	var b strings.Builder
	for i, v := range values {
		if i%16 == 0 {
			b.WriteString("\n")
		}
		b.WriteString(v + ",")
		if i%16 != 15 {
			b.WriteString(" ")
		}
	}
	return b.String() + "\n"
}

// sorted holds for every table the port binary-searches, as ICU does.
func sorted(values []string) bool {
	return slices.IsSortedFunc(values, func(a, b string) int {
		x, _ := strconv.ParseUint(a[2:], 16, 32)
		y, _ := strconv.ParseUint(b[2:], 16, 32)
		return cmp.Compare(x, y)
	})
}

func check(name string, ok bool) {
	if !ok {
		log.Fatalf("%s: unexpected shape upstream", name)
	}
}

func fetch(file string) string {
	client := &http.Client{Timeout: time.Minute}
	resp, err := client.Get(srcURL + file)
	if err != nil {
		log.Fatal(err)
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		log.Fatalf("%s: %s", file, resp.Status)
	}
	body, err := io.ReadAll(io.LimitReader(resp.Body, 1<<20))
	if err != nil {
		log.Fatal(err)
	}
	return string(body)
}
